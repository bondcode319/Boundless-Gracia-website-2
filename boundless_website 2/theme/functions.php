<?php
/**
 * Boundless Gracia Children Foundation — theme bootstrap.
 *
 * This file is intentionally thin. It defines the theme constants and loads the
 * modules in `inc/`, in dependency order. It must never contain business logic:
 * if you are tempted to add a hook here, it belongs in one of the modules.
 *
 * @package Bgcf
 * @since   1.0.0
 */

defined( 'ABSPATH' ) || exit;

/**
 * Theme version. Bump on every release; used as the default asset cache buster.
 * Keep in sync with the `Version:` header in style.css.
 */
define( 'BGCF_VERSION', '2.0.0' );

/** Absolute filesystem path to the theme root, no trailing slash. */
define( 'BGCF_DIR', get_template_directory() );

/** Public URL of the theme root, no trailing slash. */
define( 'BGCF_URI', get_template_directory_uri() );

/** Public URL of the theme asset root, no trailing slash. */
define( 'BGCF_ASSETS', BGCF_URI . '/assets' );

/**
 * Module load order (dependency order — do not shuffle without reading below).
 *
 * 1. setup          Theme supports, menus, image sizes, i18n. Everything else
 *                   assumes these exist.
 * 2. template-tags  Pure render helpers with no side effects. Loaded early so
 *                   every later module and every template can call them.
 * 2a. horizon       The Horizon layout system: the card family and the split /
 *                   photo / banner band renderers. Pure render helpers, like
 *                   template-tags, and depends on it — load order matters only
 *                   in that it must come after template-tags and before blocks,
 *                   whose partials call bgcf_card() and bgcf_split_section().
 * 2b. mega-menu     The mega-panel navigation walker and its ACF-driven item
 *                   descriptions. Defines a class and two render functions and
 *                   has no load-order dependency of its own; it sits here so the
 *                   header partial can rely on it existing.
 * 3. security       Hardening runs before anything registers public surface.
 *                   Also exposes bgcf_verify_request() used by inc/ajax.php.
 * 4. cpt            Post types and taxonomies. ACF and blocks bind to these.
 * 5. acf            Options pages, JSON sync, bgcf_field()/bgcf_option().
 *                   Field group DEFINITIONS are not a module: they live in
 *                   acf-json/ (generated by build/acf-fields.mjs) so editors can
 *                   still change them in wp-admin.
 * 6. nav            Menu walker, social icons, language switcher. Depends on
 *                   template-tags for the icon helper.
 * 7. gallery        Album taxonomy + the gallery query used by ajax and blocks.
 * 8. blocks         ACF block registration; depends on acf + template-tags.
 * 8a. patterns      The starter-page block patterns. They serialise ACF block
 *                   names and field keys, so this must load after blocks; it is
 *                   otherwise independent of everything.
 * 9. enqueue        Asset registration; may reference block handles.
 * 10. seo          Reads CPT/ACF data, so it loads after both.
 * 11. seo-schema    JSON-LD producers; attaches to the hook seo.php declares,
 *                   so it must load after it.
 * 12. leads         Subscriber/volunteer/message records. Must precede ajax,
 *                   which writes them.
 * 13. ajax          Uses security helpers, leads and gallery.
 * 14. payments      Flutterwave API client. No WordPress state of its own.
 * 15. donations     Donation records + fulfilment; depends on payments.
 * 16. campaigns     Fundraising totals, fee maths, impact lines. Reads donation
 *                   records, so it loads after donations.
 * 17. payments-routes  Public endpoints (AJAX, webhook, return URL, cron).
 *                   Depends on ajax (guard helpers), payments, donations and
 *                   campaigns (fee calculation).
 * 18. payments-admin   wp-admin screens for donations; depends on donations.
 * 18a. payments-health  Disputes, readiness checks and the Site Health test.
 *                   Depends on donations, campaigns and leads (notification).
 * 19. leads-admin   wp-admin screens and CSV export for leads.
 * 20. privacy       GDPR exporters/erasers; depends on donations and leads.
 * 21. admin         Admin-only UX; must load last so it can reorder CPT menus.
 *
 * @var string[] $bgcf_modules Module basenames, relative to inc/, without .php.
 */
$bgcf_modules = array(
	'setup',
	'template-tags',
	'horizon',
	'mega-menu',
	'security',
	'cpt',
	'acf',
	'nav',
	'gallery',
	'blocks',
	'patterns',
	'enqueue',
	'seo',
	'seo-schema',
	'leads',
	'ajax',
	'payments',
	'donations',
	'campaigns',
	'payments-routes',
	'payments-admin',
	'payments-health',
	'leads-admin',
	'privacy',
	'admin',
);

foreach ( $bgcf_modules as $bgcf_module ) {
	$bgcf_module_path = BGCF_DIR . '/inc/' . $bgcf_module . '.php';

	if ( file_exists( $bgcf_module_path ) ) {
		require_once $bgcf_module_path;
		continue;
	}

	if ( defined( 'WP_DEBUG' ) && WP_DEBUG ) {
		// Fail loudly in development, silently in production.
		trigger_error( // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_trigger_error
			sprintf(
				/* translators: %s: theme module file path. */
				esc_html__( 'BGCF: missing theme module %s', 'bgcf' ),
				esc_html( $bgcf_module_path )
			),
			E_USER_WARNING
		);
	}
}

unset( $bgcf_modules, $bgcf_module, $bgcf_module_path );
